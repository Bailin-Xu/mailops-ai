import { test, expect } from "@playwright/test";
import { browserFixtures } from "./fixtures";

let fixtures: ReturnType<typeof browserFixtures>;
test.beforeEach(() => { fixtures = browserFixtures(); });
test.afterEach(async () => { if (fixtures) await fixtures.cleanup(); });

test("revise French knowledge, compare evidence, regenerate and simulate confirmation", async ({ page }) => {
  const f = await fixtures.create({ language: "fr" });
  const external: string[] = [];
  page.on("request", (request) => { if (!new URL(request.url()).hostname.match(/^(127\.0\.0\.1|localhost)$/u)) external.push(request.url()); });
  await page.goto(`/inbox?selected=${f.threadId}`);
  const executionCount = await fixtures.executionCount();
  await page.reload();
  expect(await fixtures.executionCount()).toBe(executionCount);
  await expect(page.locator(".inbox-timeline")).toContainText("Bonjour");
  await expect(page.locator('img[src*="tracking.example.test"], script[src*="tracking.example.test"]')).toHaveCount(0);
  await page.getByRole("button", { name: "Run automatic processing", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve final text & simulate send" })).toBeVisible();
  await page.goto(`/knowledge/${f.entryId}`);
  const newAnswer = "Les commandes sont expédiées sous sept jours. Le suivi est communiqué après vérification.";
  await page.getByRole("textbox", { name: "Approved answer", exact: true }).fill(newAnswer);
  await page.getByText("Compare saved text with my proposal", { exact: true }).click();
  await expect(page.locator(".review-comparison").last()).toContainText(newAnswer);
  await page.getByRole("button", { name: "Approve & activate", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Candidate approved" })).toBeVisible();
  await expect(page.getByText("Current version 2", { exact: false })).toBeVisible();
  await page.getByRole("link", { name: "Compare version 1", exact: true }).click();
  const comparison = page.getByRole("region", { name: "Knowledge version comparison" });
  await expect(comparison).toContainText(f.answer);
  await expect(comparison).toContainText(newAnswer);
  await page.screenshot({ path: "test-results/phase-4-knowledge-review.png", fullPage: true });
  const impact = page.getByRole("region", { name: "Affected pending drafts" });
  await impact.getByRole("link", { name: f.title }).click();
  await expect(page.getByRole("button", { name: "Approve final text & simulate send" })).toHaveCount(0);
  await expect(page.getByText("Knowledge changed or historical evidence is missing.", { exact: false })).toBeVisible();
  await page.getByRole("button", { name: "Regenerate reference reply", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Final reply", exact: true })).toHaveValue(new RegExp("sept jours"));
  await page.getByRole("textbox", { name: "Final reply", exact: true }).fill("Bonjour, votre demande a été vérifiée. Merci et bonne journée.");
  await page.getByRole("button", { name: "Approve final text & simulate send", exact: true }).click();
  await expect(page.getByText("Simulated send complete", { exact: true })).toBeVisible();
  await expect(page.getByText("Human-approved final reply", { exact: false })).toBeVisible();
  expect(external).toEqual([]);
});

test("two tabs reject stale edits, retain failed text and explicitly re-review against latest", async ({ page, context }) => {
  const f = await fixtures.create();
  await page.goto(`/knowledge/${f.entryId}`);
  const second = await context.newPage();
  await second.goto(`/knowledge/${f.entryId}`);
  const proposed = "Second reviewer proposes seven day tracked shipping.";
  await second.getByRole("textbox", { name: "Approved answer", exact: true }).fill("short");
  await second.getByRole("button", { name: "Approve & activate", exact: true }).click();
  await expect(second.getByRole("alert").filter({ hasText: "at least 10 characters" })).toBeVisible();
  await expect(second.getByRole("textbox", { name: "Approved answer", exact: true })).toHaveValue("short");
  await second.getByRole("textbox", { name: "Approved answer", exact: true }).fill(proposed);
  await page.getByRole("textbox", { name: "Approved answer", exact: true }).fill("First reviewer verified five day tracked shipping.");
  await page.getByRole("button", { name: "Approve & activate", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Candidate approved" })).toBeVisible();
  await second.getByRole("button", { name: "Approve & activate", exact: true }).click();
  await expect(second.getByRole("alert").filter({ hasText: "This version changed" })).toBeVisible();
  await expect(second.getByRole("textbox", { name: "Approved answer", exact: true })).toHaveValue(proposed);
  await second.getByRole("button", { name: "Compare with latest saved version" }).click();
  await expect(second.getByRole("button", { name: "Keep my proposal against latest revision" })).toBeVisible();
  await expect(second.getByRole("button", { name: "Approve & activate", exact: true })).toBeDisabled();
  await second.getByRole("button", { name: "Keep my proposal against latest revision" }).click();
  await second.getByRole("button", { name: "Approve & activate", exact: true }).click();
  await expect(second.getByRole("status").filter({ hasText: "Candidate approved" })).toBeVisible();
  await expect(second.getByText("Current version 3", { exact: false })).toBeVisible();
  await second.getByRole("button", { name: "Reject candidate", exact: true }).click();
  await expect(second.getByRole("status").filter({ hasText: "Candidate rejected" })).toBeVisible();
  await expect(second.getByText("Current version 3 · INACTIVE", { exact: false })).toBeVisible();
  await second.getByRole("button", { name: "Approve & activate", exact: true }).click();
  await expect(second.getByText("Current version 4 · ACTIVE", { exact: false })).toBeVisible();
  await second.close();
});

